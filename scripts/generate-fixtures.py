#!/usr/bin/env python3
"""Generate original CC0 synthetic music for manual testing and genuine screenshots.
Not a reference music corpus. Never shipped as user-library data or loaded automatically.
"""
import math
import pathlib
import random
import struct
import subprocess
import wave

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / 'fixtures-generated'
DEST.mkdir(exist_ok=True)
TRACKS = [
    ('01 - Daybreak', 0.36, 116, 'wav'),
    ('02 - Soft Focus', 0.13, 120, 'flac'),
    ('03 - Night Drive', 0.24, 124, 'mp3'),
    ('04 - A Place Between', 0.085, 118, 'wav'),
    ('05 - Open Water', 0.17, 122, 'flac'),
    ('06 - After Hours', 0.28, 126, 'mp3'),
    ('07 - Slow Motion', 0.11, 112, 'wav'),
    ('08 - Light Through Glass', 0.21, 121, 'flac'),
    ('09 - The Long Way Home', 0.31, 123, 'mp3'),
    ('10 - Last Train', 0.07, 125, 'wav'),
    ('11 - Parallel Lines', 0.4, 128, 'flac'),
    ('12 - First Light', 0.15, 115, 'mp3'),
]
RATE = 44100
for index, (name, amplitude, bpm, fmt) in enumerate(TRACKS):
    path = DEST / (name + '.wav')
    rng = random.Random(index)
    frames = bytearray()
    length = 20 + index * 2
    for i in range(RATE * length):
        t = i / RATE
        beat = (t * bpm / 60) % 1
        kick = math.sin(2 * math.pi * (48 * t + 1.7 * (1 - math.exp(-beat * 35)))) * math.exp(-beat * 17)
        bass_note = [55, 65.406, 73.416, 49][int(t * bpm / 60 / 4) % 4]
        bass = math.sin(2 * math.pi * bass_note * t) * (0.3 + 0.7 * beat)
        hat = (rng.random() * 2 - 1) * math.exp(-((beat + 0.5) % 0.5) * 80) * 0.14
        phrase = 0.42 + 0.58 * math.sin(math.pi * min(1, t / 3)) if t < 3 else 0.75 + 0.25 * math.sin(t / 2.7)
        for channel in range(2):
            pad = (math.sin(2 * math.pi * bass_note * 4 * t + channel * 0.18) + 0.5 * math.sin(2 * math.pi * bass_note * 6 * t)) * 0.17
            sample = amplitude * (kick * 0.55 + bass * 0.35 + hat + pad) * phrase
            sample *= min(1, (length-t)/0.15)
            frames += struct.pack('<i', int(max(-1, min(1, sample)) * 8388607))[:3]
    with wave.open(str(path), 'wb') as out:
        out.setnchannels(2)
        out.setsampwidth(3)
        out.setframerate(RATE)
        out.writeframes(frames)
    tagged = DEST / (name + '.tagged.' + fmt)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', str(path), '-metadata', f'title={name[5:]}', '-metadata', 'artist=GainMate Test Sessions', '-metadata', 'album=Generated audio · CC0', '-metadata', 'comment=Original synthetic fixture, generated by GainMate; CC0', *(['-c:a', 'libmp3lame', '-q:a', '0'] if fmt == 'mp3' else []), str(tagged)], check=True)
    path.unlink()
    tagged.rename(DEST / (name + '.' + fmt))
print(f'Generated {len(TRACKS)} original audio fixtures in {DEST}')
